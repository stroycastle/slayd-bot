// Mini App interfeysini (jsdom da) oxirigacha sinaydi: profil → bosqichli yaratish → tarix → balans.
// Ishga tushirish: npm run test:ui
process.env.MOCK_AI = '1'; process.env.DEV_AUTH = '1'; process.env.BOT_TOKEN = '1:T'; process.env.ADMIN_IDS = '999';
const fs = require('fs'), os = require('os'), path = require('path');
const root = path.join(__dirname, '..');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ui-')); process.env.DATA_DIR = tmp; process.env.TMP_DIR = path.join(tmp, 't');
const config = require('../src/config'); const { Store } = require('../src/store'); const { createWebServer } = require('../src/web');
const { JSDOM, VirtualConsole } = require('jsdom');
const store = new Store(config.DATA_DIR);
store.ensureUser({ id: 1001, first_name: 'Ali' }); store.credit(1001, 100000, 'sinov', 'topup');
const sent = [];
const bot = { telegram: { sendDocument: async (i, f) => sent.push(f.filename), sendMessage: async () => {}, sendPhoto: async () => {} } };
const server = createWebServer({ store, bot });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  await new Promise((r) => server.listen(0, '127.0.0.1', r));
  const base = 'http://127.0.0.1:' + server.address().port;
  const html = fs.readFileSync(path.join(root, 'miniapp/index.html'), 'utf8').replace(/<script src="https:[^>]*><\/script>/, '').replace(/<script src="\/app.js"><\/script>/, '');
  const errors = [];
  const dom = new JSDOM(html, { url: base + '/?dev=1001', runScripts: 'outside-only', pretendToBeVisual: true,
    virtualConsole: new VirtualConsole().on('jsdomError', (e) => { if (!/scrollTo/.test(e.message)) errors.push(e.message); }) });
  const w = dom.window; w.fetch = (u, o) => fetch(new URL(u, base), o);
  w.eval(fs.readFileSync(path.join(root, 'miniapp/app.js'), 'utf8'));
  const text = () => w.document.getElementById('view').textContent + w.document.querySelectorAll('.foot').length;
  const all = () => w.document.body.textContent;
  const set = (sel, v) => { const el = w.document.querySelector(sel); el.value = v; el.dispatchEvent(new w.Event('input', { bubbles: true })); };
  const click = (pred) => { const b = [...w.document.querySelectorAll('button')].find(pred); if (!b) throw new Error('tugma topilmadi'); b.click(); };
  const must = (c, m) => { if (!c) { console.error('✗', m, '\nEkran:', all().slice(0, 300), '\nXatolar:', errors); process.exit(1); } console.log('✓', m); };
  await sleep(500);
  must(/Ism va familiya/.test(all()) && /Titul varagʻi koʻrinishi/.test(all()), 'profil yoʻq boʻlsa, Profil ekrani va titul koʻrinishi chiqadi');
  set('#f_fullName', 'Ali Valiyev'); set('#f_group', '101'); set('#f_university', 'OʻzDJTU'); set('#f_faculty', 'Filologiya');
  must(/Ali Valiyev/.test(w.document.querySelector('.titlecard').textContent), 'titul varagʻi oldindan koʻrinishi jonli yangilanadi');
  click((b) => b.textContent === 'Saqlash'); await sleep(600);
  must(/Yangi taqdimot/.test(all()) && /Soʻnggi ishlar/.test(all()), 'profil saqlangach, Bosh sahifa ochiladi');
  w.document.querySelector('#tabs .fab').click(); await sleep(100);
  must(/Mavzu va hajm/.test(all()) && w.document.querySelector('.foot .btn').disabled, '1-bosqich: mavzusiz “Davom etish” oʻchiq');
  set('#topic', 'Grammatik kategoriya');
  must(!w.document.querySelector('.foot .btn').disabled, 'mavzu yozilgach tugma ochiladi');
  w.document.querySelector('.range').value = 10; w.document.querySelector('.range').dispatchEvent(new w.Event('input', { bubbles: true }));
  must(/5 000/.test(all()) && !/50 000/.test(all()), 'bir xil narx: slayd soni oʻzgarsa ham 5 000 soʻm');
  w.document.querySelector('.foot .btn:last-child').click(); await sleep(100);
  must(/Koʻrinish/.test(all()), '2-bosqich: til va rang');
  w.document.querySelectorAll('.opt')[3].click(); await sleep(50);
  w.document.querySelectorAll('.sw')[1].click(); await sleep(50);
  must(/Koʻrinish \(20 xil\)/.test(all()) && w.document.querySelectorAll('.styles .chip').length === 21, '2-bosqich: 20 ta koʻrinish + tasodifiy');
  w.document.querySelectorAll('.styles .chip')[4].click(); await sleep(50);
  must(w.document.querySelectorAll('.styles .chip')[4].classList.contains('on') && /4\. Tungi/.test(w.document.querySelectorAll('.styles .chip')[4].textContent), 'koʻrinish tanlandi (Tungi)');
  click((b) => /Namunalarni koʻrish/.test(b.textContent)); await sleep(50);
  must(/^\/previews\/\w+\.jpg$/.test(new URL(w.document.querySelector('.lightbox img').src).pathname), 'namunalar rasmi ochiladi');
  w.document.querySelector('.lightbox .icon-btn').click(); await sleep(30);
  must(!w.document.querySelector('.lightbox'), 'namunalar oynasi yopiladi');
  w.document.querySelector('.foot .btn:last-child').click(); await sleep(100);
  must(/Buyurtma/.test(all()) && /Qaraqalpaqsha/.test(all()) && /Tungi/.test(all()) && /Yasash · 5 000/.test(all()), '3-bosqich: buyurtma xulosasi (til, koʻrinish) va narx');
  w.document.getElementById('go').click(); await sleep(900);
  must(/Buyurtma qabul qilindi/.test(all()), 'buyurtmadan keyin “qabul qilindi” ekrani');
  must(store.db.orders[0].style === 'tungi' && store.db.orders[0].lang === 'kaa' && store.getUser(1001).balance === 95000, 'serverda: koʻrinish tungi, til kaa, 5 000 yechildi');
  click((b) => b.textContent === 'Jarayonni koʻrish'); await sleep(700);
  must(/Buyurtmalarim/.test(all()), 'Tarix ekrani ochiladi');
  for (let i = 0; i < 40 && !/Chatga qayta yuborish/.test(all()); i++) await sleep(500);
  must(/Tayyor/.test(all()) && /Chatga qayta yuborish/.test(all()), 'taqdimot tayyor boʻladi');
  must(sent.some((f) => f.endsWith('.pptx')), 'fayl chatga yuborildi');
  w.document.querySelectorAll('#tabs .t')[2].click(); await sleep(600);
  must(/Joriy balans/.test(all()) && /Harakatlar/.test(all()), 'Balans ekrani va harakatlar roʻyxati');
  w.document.querySelectorAll('.amount')[1].click();
  click((b) => /Balansni toʻldirish/.test(b.textContent)); await sleep(500);
  must(/0000 0000 0000 0000/.test(all()) && /Chek rasmini yuborish/.test(all()), 'toʻlov rekvizitlari va chek tugmasi');
  must(errors.length === 0, 'skriptda xato yoʻq ' + JSON.stringify(errors));
  server.close(); process.exit(0);
})().catch((e) => { console.error(e); process.exit(1); });
